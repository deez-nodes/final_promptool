#!/usr/bin/env node
/**
 * scripts/gen-tokens.mjs — writes the app's color and glow tokens from myfiles/tokens.json.
 *
 *   node scripts/gen-tokens.mjs          (npm run tokens)
 *
 * myfiles/tokens.json is the single source. This script rewrites, between the
 * BEGIN/END generated markers:
 *   - tailwind.config.ts   theme.extend.colors and theme.extend.boxShadow
 *   - assets/css/main.css  the :root custom properties (--<color>, --<shadow>)
 *
 * Everything outside the markers is left alone. A file is only written when its
 * generated region actually changes, so running the script twice is a no-op.
 * checks/tokens.mjs imports render() to fail when a generated region is stale.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DEFAULT_ROOT = path.resolve(HERE, '..');

export const TOKENS_FILE = 'myfiles/tokens.json';
export const TAILWIND_FILE = 'tailwind.config.ts';
export const CSS_FILE = 'assets/css/main.css';

const NOTE = 'generated by scripts/gen-tokens.mjs from myfiles/tokens.json (npm run tokens). Do not edit by hand.';
const TS_BEGIN = `// BEGIN ${NOTE}`;
const TS_END = '// END generated';
const CSS_BEGIN = `/* BEGIN ${NOTE} */`;
const CSS_END = '/* END generated */';

export function loadTokens(root = DEFAULT_ROOT) {
  return JSON.parse(fs.readFileSync(path.join(root, TOKENS_FILE), 'utf8'));
}

const tsKey = k => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`);

/** Object entries of a token group as [name, value] pairs, in file order. */
const entries = group => Object.entries(group || {}).map(([k, v]) => [k, v.value]);

function renderTailwind(tokens, indent) {
  const block = (name, pairs) => [
    `${indent}${name}: {`,
    pairs.map(([k, v]) => `${indent}  ${tsKey(k)}: '${v}'`).join(',\n'),
    `${indent}},`,
  ].join('\n');
  return [
    block('colors', entries(tokens.color)),
    block('boxShadow', entries(tokens.shadow)),
  ].join('\n');
}

function renderCss(tokens) {
  const vars = [...entries(tokens.color), ...entries(tokens.shadow)]
    .map(([k, v]) => `  --${k}: ${v};`);
  return [':root {', ...vars, '}'].join('\n');
}

/**
 * Replace the text between a BEGIN line and an END line. The BEGIN line's
 * indentation is reused for the END line and handed to the renderer.
 */
function splice(text, begin, end, renderBody, file) {
  const b = text.indexOf(begin);
  const e = text.indexOf(end, b + 1);
  if (b < 0 || e < 0) throw new Error(`${file}: missing generated-region markers (${begin} … ${end})`);
  const lineStart = text.lastIndexOf('\n', b) + 1;
  const indent = text.slice(lineStart, b);
  const head = text.slice(0, b + begin.length);
  const tail = text.slice(e);
  return `${head}\n${renderBody(indent)}\n${indent}${tail}`;
}

/** Returns { [relPath]: { before, after } } for every generated file. */
export function render(root = DEFAULT_ROOT) {
  const tokens = loadTokens(root);
  const out = {};
  const tw = fs.readFileSync(path.join(root, TAILWIND_FILE), 'utf8');
  out[TAILWIND_FILE] = { before: tw, after: splice(tw, TS_BEGIN, TS_END, ind => renderTailwind(tokens, ind), TAILWIND_FILE) };
  const css = fs.readFileSync(path.join(root, CSS_FILE), 'utf8');
  out[CSS_FILE] = { before: css, after: splice(css, CSS_BEGIN, CSS_END, () => renderCss(tokens), CSS_FILE) };
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(process.argv[2] || DEFAULT_ROOT);
  for (const [rel, { before, after }] of Object.entries(render(root))) {
    if (before === after) {
      console.log(`unchanged  ${rel}`);
    } else {
      fs.writeFileSync(path.join(root, rel), after);
      console.log(`wrote      ${rel}`);
    }
  }
}
