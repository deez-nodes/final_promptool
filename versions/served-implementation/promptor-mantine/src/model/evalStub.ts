import { buildOutput } from './build'
import { templateOf } from './items'
import type { Grader, Item, OutputFormat } from './types'

interface GraderSpec {
  name: string
  criteria: string
  cases: string[]
  fn: string
}

const GRADERS: Record<Grader, GraderSpec> = {
  json: {
    name: 'grade_json',
    criteria: `- Output is 100% valid & matches the expected shape (E-S1)
- Accuracy >= {{0.90}} on the seed set (E-S2 — set threshold)
- 0 spurious fields / hallucinated labels (E-S4)`,
    cases: [
      `{"input": "{{typical 1}}",        "expected": "{{answer}}"},`,
      `{"input": "{{typical 2}}",        "expected": "{{answer}}"},`,
      `{"input": "",                     "expected": "{{answer}}"},   # edge: empty`,
      `{"input": "{{very long input}}",  "expected": "{{answer}}"},   # edge: length`,
      `{"input": "{{ambiguous}}",        "expected": "{{answer}}"},   # edge: humans disagree`,
    ],
    fn: `def grade_json(out, case):            # E-G1 code: valid JSON w/ required keys
    import json
    try: obj = json.loads(out)
    except json.JSONDecodeError: return False
    return all(k in obj for k in case.get("required_keys", []))`,
  },
  code: {
    name: 'grade_code',
    criteria: `- All listed tests pass (E-G1 code-based)
- Solution is general, not hard-coded (I3)
- No edits outside declared scope (I2)`,
    cases: [
      `{"input": "{{run: pytest -q}}",        "expected": "all pass"},`,
      `{"input": "{{run: ruff / typecheck}}", "expected": "clean"},`,
      `{"input": "{{edge: empty/malformed}}", "expected": "handled, no crash"},  # edge`,
      `{"input": "{{edge: boundary value}}",  "expected": "correct"},            # edge`,
    ],
    fn: `def grade_code(out, case):            # E-G1 code: wire to your test runner
    # e.g. subprocess.run(["pytest","-q"]).returncode == 0
    return "{{assert}}" in out`,
  },
  llm: {
    name: 'grade_llm',
    criteria: `- Judge rates >= {{4}}/5 (or 'correct') vs the rubric (E-G3)
- >= {{0.90}} of the seed set passes (E-S2)
- Hard constraints (length/sections) also pass a cheap code check`,
    cases: [
      `{"input": "{{typical 1}}",        "rubric": "{{what a good answer must contain}}"},`,
      `{"input": "{{typical 2}}",        "rubric": "{{...}}"},`,
      `{"input": "",                     "rubric": "{{handles empty input gracefully}}"},   # edge`,
      `{"input": "{{very long}}",        "rubric": "{{stays on task}}"},                    # edge`,
      `{"input": "{{adversarial}}",      "rubric": "{{refuses or redirects}}"},             # edge`,
    ],
    fn: `def grade_llm(out, case):             # E-G3 LLM-as-judge: reason then verdict
    p = (f"Grade the answer against the rubric.\\n<rubric>{case['rubric']}</rubric>\\n"
         f"<answer>{out}</answer>\\nThink in <thinking> tags, then output exactly "
         f"'correct' or 'incorrect' in <result> tags.")
    v = client.messages.create(model=GRADER_MODEL, max_tokens=1024,
            messages=[{"role":"user","content":p}]).content[0].text.lower()
    return "<result>correct</result>" in v`,
  },
}

/** A Markdown note with success criteria and a runnable Python eval harness for the item's prompt. */
export function generateEval(item: Item, fmt: OutputFormat): string {
  const tpl = templateOf(item)
  const grader = GRADERS[tpl.evalGrader ?? 'llm']
  const name = item.name || tpl.label
  const system = buildOutput(item, fmt).replace(/"""/g, "'''")

  const py = `"""Eval stub for: ${name}
Auto-generated by prompTOR. Grader: ${grader.name} (template '${item.template}').
  pip install anthropic ; export ANTHROPIC_API_KEY=... ; python eval_${item.template}.py
"""
import anthropic
client = anthropic.Anthropic()

CANDIDATE_MODEL = "claude-opus-4-8"
GRADER_MODEL    = "claude-opus-4-8"   # E-G3.4: prefer a separate grader

SYSTEM_PROMPT = """${system}"""

# E-D1: typical + labeled edge cases.  E-D3: seed — expand to dozens.
TEST_CASES = [
    ${grader.cases.join('\n    ')}
]

${grader.fn}

def get_completion(test_input):
    return client.messages.create(
        model=CANDIDATE_MODEL, max_tokens=1024, system=SYSTEM_PROMPT,
        messages=[{"role":"user","content":str(test_input)}],
    ).content[0].text

def main():
    ok = 0
    for case in TEST_CASES:
        out = get_completion(case["input"])
        v = ${grader.name}(out, case)
        passed = v is True
        ok += passed
        print(("PASS" if passed else "FAIL"), repr(str(case["input"])[:48]))
    print(f"\\nScore: {ok/len(TEST_CASES)*100:.1f}%  ({ok}/{len(TEST_CASES)})")

if __name__ == "__main__":
    main()
`

  return `# Eval stub — ${name}
# grader: ${grader.name} (auto-selected from template)

# Success criteria (S·M·A·R)
${grader.criteria}

# Runnable harness (eval_${item.template}.py)
\`\`\`python
${py}\`\`\`
`
}
